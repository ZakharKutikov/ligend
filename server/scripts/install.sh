    fi

    # Panel HTML — embed if exists in script directory, otherwise download
    if [[ -f "panel/index.html" ]]; then
        cp "panel/index.html" "${INSTALL_DIR}/panel/index.html"
    elif [[ -f "/tmp/ligend-panel/index.html" ]]; then
        cp "/tmp/ligend-panel/index.html" "${INSTALL_DIR}/panel/index.html"
    fi

    ok "Конфигурация создана: ${INSTALL_DIR}/ligend.yaml"
}

# ── Setup networking ──
setup_network() {
    info "Настройка сети..."

    # Enable IP forwarding
    sysctl -w net.ipv4.ip_forward=1 > /dev/null
    echo "net.ipv4.ip_forward=1" > /etc/sysctl.d/99-ligend.conf
    sysctl -p /etc/sysctl.d/99-ligend.conf > /dev/null 2>&1

    # NAT masquerade
    DEFAULT_IFACE=$(ip route show default | awk '/default/ {print $5}' | head -1)
    if [[ -n "$DEFAULT_IFACE" ]]; then
        iptables -t nat -C POSTROUTING -s 10.8.0.0/24 -o "$DEFAULT_IFACE" -j MASQUERADE 2>/dev/null || \
        iptables -t nat -A POSTROUTING -s 10.8.0.0/24 -o "$DEFAULT_IFACE" -j MASQUERADE
        ok "NAT настроен на интерфейсе $DEFAULT_IFACE"
    else
        warn "Не удалось определить сетевой интерфейс, настройте NAT вручную"
    fi

    # Save iptables
    iptables-save > /etc/iptables/rules.v4 2>/dev/null || true

    # UFW (if installed)
    if command -v ufw &>/dev/null; then
        ufw allow 80/tcp > /dev/null 2>&1 || true
        ufw allow 443/tcp > /dev/null 2>&1 || true
        ufw allow 51820/udp > /dev/null 2>&1 || true
        ufw allow 8443/tcp > /dev/null 2>&1 || true
    fi

    ok "Сеть настроена"
}

# ── Setup Nginx ──
setup_nginx() {
    DOMAIN=""
    VPS_IP=$(curl -s4 ifconfig.me 2>/dev/null || curl -s4 icanhazip.com 2>/dev/null || hostname -I | awk '{print $1}')

    echo ""
    echo -e "${BOLD}Настройка домена${NC}"
    echo -e "  Введите домен (например: vpn.example.com)"
    echo -e "  Или нажмите ${CYAN}[Enter]${NC} для работы без домена (по IP)"
    echo -n "  Домен: "
    read -r DOMAIN

    if [[ -n "$DOMAIN" ]]; then
        info "Настройка Nginx с SSL для ${DOMAIN}..."

        cat > /etc/nginx/sites-available/ligend <<EOF
server {
    listen 80;
    server_name ${DOMAIN};
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl http2;
    server_name ${DOMAIN};

    ssl_certificate /etc/letsencrypt/live/${DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${DOMAIN}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_session_cache shared:SSL:10m;

    location ${WS_PATH} {
        proxy_pass http://127.0.0.1:8443;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
        proxy_cache off;
    }

    location / {
        proxy_pass http://127.0.0.1:8443;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
    }
}
EOF
        ln -sf /etc/nginx/sites-available/ligend /etc/nginx/sites-enabled/ligend
        rm -f /etc/nginx/sites-enabled/default

        # Get SSL certificate
        certbot --nginx -d "${DOMAIN}" --non-interactive --agree-tos --register-unsafely-without-email 2>/dev/null || \
        certbot certonly --standalone -d "${DOMAIN}" --non-interactive --agree-tos --register-unsafely-without-email 2>/dev/null || \
        warn "Не удалось получить SSL сертификат. Настройте вручную: certbot --nginx -d ${DOMAIN}"

        nginx -t > /dev/null 2>&1 && systemctl restart nginx
        ok "Nginx + SSL настроен для ${DOMAIN}"
    else
        info "Работа без домена (прямое подключение по IP:8443)"
        # Remove default nginx site to free port 80
        rm -f /etc/nginx/sites-enabled/default
        systemctl stop nginx 2>/dev/null || true
        systemctl disable nginx 2>/dev/null || true
        ok "Nginx отключен (прямое подключение)"
    fi
}

# ── Install systemd service ──
install_service() {
    info "Установка systemd сервиса..."

    cat > "${SERVICE_FILE}" <<EOF
[Unit]
Description=Ligend VPN Server (GOmp Studios)
After=network.target
Wants=network-online.target

[Service]
Type=simple
User=root
Group=root
ExecStart=${BIN_DIR}/ligend-server -config ${INSTALL_DIR}/ligend.yaml
Restart=always
RestartSec=5
LimitNOFILE=65536
LimitNPROC=4096

StandardOutput=journal
StandardError=journal
SyslogIdentifier=ligend

[Install]
WantedBy=multi-user.target
EOF

    systemctl daemon-reload
    systemctl enable ligend > /dev/null 2>&1
    systemctl restart ligend

    # Wait for panel to start
    sleep 3

    ok "Сервис ligend.service установлен и запущен"
}

# ── Get panel port from logs ──
get_panel_port() {
    PANEL_PORT=$(journalctl -u ligend -n 20 --no-pager 2>/dev/null | grep -oP 'URL: http://0\.0\.0\.0:\K[0-9]+' | tail -1)
    if [[ -z "$PANEL_PORT" ]]; then
        PANEL_PORT="(см. journalctl -u ligend)"
    fi
}

