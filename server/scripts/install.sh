# Generated by GOmp Studios Installer v${LIGEND_VERSION}
# $(date -Iseconds)

listen_addr: ":8443"
udp_port: 51820
game_mode: true
ws_path: "${WS_PATH}"
secret_key: "${SECRET_KEY}"
vpn_subnet: "10.8.0.0/24"
tun_name: "ligend0"
mtu: 1280
dns:
  - "1.1.1.1"
  - "8.8.8.8"
web_root: "${INSTALL_DIR}/web"
padding_min_sec: 3
padding_max_sec: 15
max_clients: 254
awg_jc: 4
awg_jmin: 40
awg_jmax: 70
EOF
    chmod 600 "${INSTALL_DIR}/ligend.yaml"

    # Cover website (decoy)
    if [[ ! -f "${INSTALL_DIR}/web/index.html" ]]; then
        cat > "${INSTALL_DIR}/web/index.html" <<'WEBEOF'
<!DOCTYPE html><html><head><meta charset="utf-8"><title>CloudDev Notes</title>
<style>body{font-family:system-ui;max-width:800px;margin:50px auto;padding:20px;color:#333;line-height:1.6}
h1{color:#1a73e8}a{color:#1a73e8}.post{border-bottom:1px solid #eee;padding:20px 0}</style></head>
<body><h1>CloudDev Notes</h1><p>Блог о технологиях и облачной разработке</p>
<div class="post"><h2>Kubernetes Best Practices 2026</h2><p>Обзор лучших практик для production кластеров...</p></div>
<div class="post"><h2>Оптимизация PostgreSQL</h2><p>Тюнинг запросов и индексов для высоконагруженных проектов...</p></div>
<div class="post"><h2>CI/CD с GitHub Actions</h2><p>Автоматизация деплоя через GitHub Actions и ArgoCD...</p></div>
<footer style="margin-top:40px;color:#999">&copy; 2026 CloudDev Notes. All rights reserved.</footer></body></html>
