#
set -euo pipefail

# ── Colors ──
RED='\033[0;31m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
PURPLE='\033[0;35m'
BOLD='\033[1m'
NC='\033[0m'

LIGEND_VERSION="3.5.0"
INSTALL_DIR="/etc/ligend"
BIN_DIR="/usr/local/bin"
SERVICE_FILE="/etc/systemd/system/ligend.service"
BINARY_URL="https://github.com/ZakharKutikov/ligend/releases/latest/download/ligend-server-linux-amd64"

# ── Helpers ──
info()  { echo -e "${CYAN}[INFO]${NC}  $1"; }
ok()    { echo -e "${GREEN}[OK]${NC}    $1"; }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $1"; }
fail()  { echo -e "${RED}[FAIL]${NC}  $1"; exit 1; }

banner() {
    echo -e "${PURPLE}"
    echo "  ╔════════════════════════════════════════════╗"
    echo "  ║   ⚡  Ligend VPN Installer v${LIGEND_VERSION}         ║"
    echo "  ║   by GOmp Studios                         ║"
    echo "  ╚════════════════════════════════════════════╝"
    echo -e "${NC}"
}

# ── Pre-flight checks ──
preflight() {
    if [[ $EUID -ne 0 ]]; then
        fail "Запустите от root: sudo bash install.sh"
    fi

    if ! command -v apt-get &>/dev/null; then
        fail "Поддерживаются только Ubuntu 20+ / Debian 11+"
    fi

    ARCH=$(uname -m)
    if [[ "$ARCH" != "x86_64" && "$ARCH" != "amd64" ]]; then
        fail "Поддерживается только amd64 (x86_64), у вас: $ARCH"
    fi

    info "Система: $(lsb_release -ds 2>/dev/null || cat /etc/os-release | grep PRETTY_NAME | cut -d= -f2 | tr -d '\"') ($ARCH)"
}

# ── Install dependencies ──
install_deps() {
    info "Установка зависимостей..."
    
    # Kill any stale apt processes & locks
    rm -f /var/lib/apt/lists/lock /var/cache/apt/archives/lock /var/lib/dpkg/lock* 2>/dev/null || true

    # Pre-seed iptables-persistent to avoid interactive debconf prompts hanging
    echo iptables-persistent iptables-persistent/autosave_v4 boolean true | debconf-set-selections 2>/dev/null || true
    echo iptables-persistent iptables-persistent/autosave_v6 boolean true | debconf-set-selections 2>/dev/null || true

    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y -q
    apt-get install -y -q -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold" \
        curl wget nginx certbot python3-certbot-nginx iptables iptables-persistent net-tools
    ok "Зависимости установлены"
}

# ── Download binary ──
download_binary() {
    info "Подготовка Ligend Server v${LIGEND_VERSION}..."
    mkdir -p "${BIN_DIR}"

    # 1. Check if binary already in /usr/local/bin
    if [[ -f "${BIN_DIR}/ligend-server" ]] && [[ -x "${BIN_DIR}/ligend-server" ]]; then
        ok "Используется установленный бинарник: ${BIN_DIR}/ligend-server"
        return 0
    fi

    # 2. Check current directory
    if [[ -f "./ligend-server-linux" ]]; then
        cp "./ligend-server-linux" "${BIN_DIR}/ligend-server"
        chmod +x "${BIN_DIR}/ligend-server"
        ok "Бинарник скопирован из текущей папки: ${BIN_DIR}/ligend-server"
        return 0
    fi

    # 3. Check /root/ligend-server-linux
    if [[ -f "/root/ligend-server-linux" ]]; then
        cp "/root/ligend-server-linux" "${BIN_DIR}/ligend-server"
        chmod +x "${BIN_DIR}/ligend-server"
        ok "Бинарник скопирован из /root: ${BIN_DIR}/ligend-server"
        return 0
    fi

    # 4. Try downloading from GitHub
    info "Попытка скачивания с GitHub..."
    if curl -fsSL --connect-timeout 10 -o "${BIN_DIR}/ligend-server" "${BINARY_URL}" 2>/dev/null; then
        chmod +x "${BIN_DIR}/ligend-server"
        ok "Бинарник скачан с GitHub: ${BIN_DIR}/ligend-server"
        return 0
    fi

    fail "Бинарник ligend-server не найден на сервере! Загрузите его: scp server/ligend-server-linux root@$(hostname -I | awk '{print $1}'):/usr/local/bin/ligend-server"
}

# ── Generate keys ──
generate_keys() {
    SECRET_KEY=$(openssl rand -base64 32)
    WS_PATH="/ws-$(openssl rand -hex 8)"
    ok "Ключи сгенерированы"
}

# ── Create config files ──
create_config() {
    info "Создание конфигурации..."

    mkdir -p "${INSTALL_DIR}/panel"
    mkdir -p "${INSTALL_DIR}/web"

    # Main config
    cat > "${INSTALL_DIR}/ligend.yaml" <<EOF
